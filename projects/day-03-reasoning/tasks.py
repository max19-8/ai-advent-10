def grade_answer(text, task):
    """Проверяется только последняя строка, а не числа внутри объяснения."""
    lines = text.strip().splitlines()
    last = lines[-1].strip().replace("**", "") if lines else ""
    units = {
        "notebook": r"(?:руб(?:\.|ль|ля|лей)?|₽)",
        "pumps": r"(?:час(?:а|ов)?|ч\.?)",
        "machines": r"(?:мин(?:\.|ута|уты|ут)?)",
        "bridge": r"(?:мин(?:\.|ута|уты|ут)?)",
        "knapsack": r"(?:балл(?:а|ов)?)",
        "route": r"(?:руб(?:\.|ль|ля|лей)?|₽)",
        "route_simple": r"(?:руб(?:\.|ль|ля|лей)?|₽)",
    }
    match = re.fullmatch(
        r"Ответ:\s*([+-]?(?:\d+(?:[.,]\d+)?|[.,]\d+))"
        + r"(?:\s*" + units[task["id"]] + r")?\.?",
        last, flags=re.IGNORECASE,
    )
    if not match:
        return {"status": "review", "value": None}
    value = Decimal(match.group(1).replace(",", "."))
    return {
        "status": "correct" if value == Decimal(task["expected"]) else "wrong",
        "value": str(value),
    }
